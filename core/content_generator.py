    def __init__(self):
        """Инициализация генератора контента."""
        self.current_theme_index = 0
        self.themes = list(ContentTheme)
        random.shuffle(self.themes)
        logger.info(f"✅ ContentGenerator инициализирован с {len(self.themes)} темами")
    
    def get_next_theme(self) -> ContentTheme:
        """Получить следующую тему в цикле."""
        theme = self.themes[self.current_theme_index]
        self.current_theme_index = (self.current_theme_index + 1) % len(self.themes)
        return theme
    
    def generate_content(self) -> Dict[str, str]:
        """
        Генерировать контент для следующей публикации.
        
        Returns:
            Dict с полями: title, description, platform
        """
        theme = self.get_next_theme()
        template = self.CONTENT_TEMPLATES.get(theme, {})
        
        title = template.get("title", f"Тема: {theme.value}")
        templates = template.get("templates", [])
        description = random.choice(templates) if templates else f"Контент по теме {theme.value}"
        
        # Дополнить контент с фокусом на привлечение пользователей
        cta = self._get_call_to_action()
        full_description = f"{description}\n\n{cta}"
        
        return {
            "title": title,
            "description": full_description,
            "theme": theme.value,
            "platform": "multi",  # Для всех платформ
        }
    
